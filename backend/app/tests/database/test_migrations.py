"""Tests for the Alembic migrations (D-023).

Behaviour: the test run builds the schema from the migrations on a database
whose name ends in "_test" (and refuses any other database), the SQLAlchemy
models match the migrations exactly, and every migration can be undone and
redone.
"""

import pytest
from alembic import command
from sqlalchemy import Engine

from app.tests.db_support import alembic_config, assert_is_test_database


@pytest.mark.parametrize("name", ["schoolflow", "neondb", "schoolflow_test_backup", "test"])
def test_refuses_to_reset_a_database_not_named_test(name: str) -> None:
    # Denied case: the reset wipes everything, so it only runs on *_test.
    with pytest.raises(RuntimeError, match="only resets a database whose name ends in _test"):
        assert_is_test_database(name)


def test_accepts_the_test_database() -> None:
    assert_is_test_database("schoolflow_test")


def test_models_match_migrations(db_engine: Engine) -> None:
    # Fails with AutogenerateDiffsDetected if a model changed without a migration.
    with db_engine.connect() as connection:
        command.check(alembic_config(connection))


def test_every_migration_can_be_undone_and_redone(db_engine: Engine) -> None:
    # PostgreSQL can roll back table changes, so this runs inside a transaction
    # that is thrown away: the shared test schema is left as it was.
    with db_engine.connect() as connection:
        transaction = connection.begin()
        try:
            config = alembic_config(connection)
            command.downgrade(config, "base")
            command.upgrade(config, "head")
        finally:
            transaction.rollback()
